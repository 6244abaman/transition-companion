export function mountDesk({ document: doc = document, fetcher = fetch } = {}) {
  const $ = (id) => doc.getElementById(id);
  let language = "he",
    session,
    items = [],
    selected,
    busy = false,
    detailGeneration = 0;
  const t = (key) => COPY[language][key] || key;
  const el = (tag, text, cls) => {
    const n = doc.createElement(tag);
    if (text !== undefined) n.textContent = text;
    if (cls) n.className = cls;
    return n;
  };
  const button = (text, action, cls) => {
    const b = el("button", text, cls);
    b.type = "button";
    b.onclick = action;
    return b;
  };
  function status(text, error = false) {
    $("status").textContent = text;
    $("status").className = error ? "error" : "";
  }
  async function api(path, method = "GET", data) {
    const r = await fetcher("/staff/api/" + path, {
      method,
      credentials: "same-origin",
      headers:
        method === "POST"
          ? {
              "Content-Type": "application/json",
              "X-CSRF-Token": session?.csrf || "",
            }
          : {},
      ...(data ? { body: JSON.stringify(data) } : {}),
    });
    if (!r.ok) {
      if (r.status === 401) {
        session = undefined;
        showSession();
      }
      const message = (await r.json().catch(() => ({}))).error;
      throw { status: r.status, message };
    }
    return r.json();
  }
  function error(e) {
    status(
      t(
        e.status === 409 ? "conflict" : e.status === 401 ? "session" : "error",
      ) + (e.status === 400 && e.message ? " " + e.message : ""),
      true,
    );
  }
  function state(item) {
    return item.status === "approved" && new Date(item.expires_at) <= new Date()
      ? "expired"
      : item.status;
  }
  function badge(item) {
    return el("span", t(state(item)), "badge " + state(item));
  }
  function link(url, label) {
    const a = el("a", label);
    a.href = url;
    a.target = "_blank";
    a.rel = "noopener noreferrer";
    return a;
  }
  function renderCopy() {
    doc.documentElement.lang = language;
    doc.documentElement.dir = language === "he" ? "rtl" : "ltr";
    $("language").textContent = language === "he" ? "English" : "עברית";
    for (const [id, key] of Object.entries({
      eyebrow: "eyebrow",
      heading: "heading",
      intro: "intro",
      "login-title": "loginTitle",
      "username-label": "username",
      "password-label": "password",
      "login-button": "login",
      logout: "logout",
      "setup-help": "setup",
      "preview-heading": "preview",
      "preview-note": "pending",
      footer: "footer",
      new: "new",
      refresh: "refresh",
      "filter-label": "filter",
    }))
      $(id).textContent = t(key);
    for (const option of $("filter").options)
      option.textContent = t(option.value);
    showSession();
    renderQueue();
  }
  function showSession() {
    $("workspace").hidden = !session;
    $("login-area").hidden = !!session;
    $("logout").hidden = !session;
    if (session) {
      $("identity").textContent =
        `${session.staff.display_name} · ${t(session.staff.role)} · ${session.staff.professional_role}`;
      $("new").hidden = session.staff.role !== "editor";
    }
  }
  function renderQueue() {
    const queue = $("queue");
    queue.replaceChildren();
    const filter = $("filter").value,
      shown = items.filter((x) => filter === "all" || state(x) === filter);
    if (!shown.length) {
      queue.append(el("p", t("empty")));
      return;
    }
    for (const item of shown) {
      const b = button(
        item.content.title[language],
        () => void select(item.id).catch(error),
        item.id === selected ? "active" : "",
      );
      b.append(
        el("small", `${t("version")} ${item.version} · ${item.topic_id}`),
        badge(item),
      );
      queue.append(b);
    }
  }
  async function refresh() {
    items = (await api("revisions")).items;
    renderQueue();
    if (selected) await select(selected);
  }
  async function select(id) {
    selected = id;
    const request = ++detailGeneration;
    const item = await api("revisions/" + id);
    if (request !== detailGeneration || !session) return;
    renderQueue();
    renderDetail(item);
  }
  function input(
    parent,
    label,
    value = "",
    { type = "text", max = 1000, dir } = {},
  ) {
    const wrap = el("label", label),
      n = el(type === "textarea" ? "textarea" : "input");
    if (type !== "textarea") n.type = type;
    n.value = value;
    n.maxLength = max;
    if (dir) n.dir = dir;
    wrap.append(n);
    parent.append(wrap);
    return n;
  }
  function editFields(parent, c, create = false) {
    const topic = input(parent, t("topic"), c.topicId, { max: 80, dir: "ltr" });
    topic.disabled = !create;
    const label = el("label", t("domain")),
      domain = el("select");
    for (const key of ["benefits", "education", "employment", "general"]) {
      const o = el("option", t(key));
      o.value = key;
      domain.append(o);
    }
    domain.value = c.domain;
    label.append(domain);
    parent.append(label);
    const groups = {},
      bilingual = el("div", undefined, "bilingual");
    for (const lang of ["he", "en"]) {
      const section = el("section");
      section.lang = lang;
      section.dir = lang === "he" ? "rtl" : "ltr";
      section.append(el("h3", lang === "he" ? "עברית" : "English"));
      groups[lang] = {
        title: input(section, t("title"), c.title[lang], { max: 200 }),
        body: input(section, t("body"), c.body[lang], {
          type: "textarea",
          max: 3000,
        }),
        scope: input(section, t("scope"), c.scope[lang], {
          type: "textarea",
          max: 1000,
        }),
      };
      bilingual.append(section);
    }
    parent.append(bilingual);
    const source = el("div", undefined, "source-box");
    if (c.source.url) source.append(link(c.source.url, t("source")));
    const url = input(source, t("source"), c.source.url, {
        type: "url",
        max: 1000,
        dir: "ltr",
      }),
      publisher = input(source, t("publisher"), c.source.publisher, {
        max: 200,
      }),
      checked = input(source, t("checked"), c.source.checkedAt, {
        type: "date",
      }),
      evidence = input(source, t("evidence"), c.source.evidence, {
        type: "textarea",
        max: 1200,
      });
    parent.append(source);
    return () => ({
      topicId: topic.value,
      domain: domain.value,
      title: { he: groups.he.title.value, en: groups.en.title.value },
      body: { he: groups.he.body.value, en: groups.en.body.value },
      scope: { he: groups.he.scope.value, en: groups.en.scope.value },
      source: {
        url: url.value,
        publisher: publisher.value,
        checkedAt: checked.value,
        evidence: evidence.value,
      },
    });
  }
  async function action(item, verb, data = {}) {
    if (busy) return;
    busy = true;
    const buttons = [...$("detail").querySelectorAll("button")];
    for (const b of buttons) b.disabled = true;
    try {
      const result = await api(`revisions/${item.id}/${verb}`, "POST", {
        expectedVersion: item.lock_version,
        ...data,
      });
      selected = result.id;
      await refresh();
      status(t("success"));
    } catch (e) {
      error(e);
    } finally {
      busy = false;
      for (const b of buttons) b.disabled = false;
    }
  }
  function renderDetail(item) {
    const area = $("detail");
    area.replaceChildren(
      el("h2", item.content.title[language]),
      badge(item),
      el("p", `${t("version")} ${item.version} · ${item.topic_id}`),
      el("p", t("publicOnly"), "small"),
    );
    const editor = session.staff.role === "editor",
      reviewer = session.staff.role === "reviewer",
      c = item.content;
    let read;
    if (editor && item.status === "draft") read = editFields(area, c);
    else {
      const bilingual = el("div", undefined, "bilingual");
      for (const lang of ["he", "en"]) {
        const section = el("section");
        section.lang = lang;
        section.dir = lang === "he" ? "rtl" : "ltr";
        section.append(
          el("h3", c.title[lang]),
          el("p", c.body[lang]),
          el("p", c.scope[lang], "note"),
        );
        bilingual.append(section);
      }
      area.append(bilingual);
      const source = el("div", undefined, "source-box");
      source.append(
        link(c.source.url, t("source")),
        el("p", c.source.publisher),
        el("p", t("checked") + ": " + c.source.checkedAt),
        el("p", c.source.evidence),
      );
      area.append(source);
    }
    if (item.reviewed_at)
      area.append(
        el(
          "p",
          `${t("reviewed")}: ${new Date(item.reviewed_at).toLocaleString(language)} · ${t("expiry")}: ${new Date(item.expires_at).toLocaleDateString(language)}`,
        ),
      );
    const actions = el("div", undefined, "actions");
    if (editor && item.status === "draft") {
      const initialDraft = JSON.stringify(read());
      area.append(el("p", t("draftFirst"), "note"));
      actions.append(
        button(
          t("save"),
          () => void action(item, "save", { content: read() }),
          "primary",
        ),
        button(t("submit"), () => {
          if (JSON.stringify(read()) !== initialDraft) {
            status(t("draftFirst"), true);
            return;
          }
          void action(item, "submit");
        }),
      );
    }
    if (
      editor &&
      ["approved", "rejected", "withdrawn", "superseded"].includes(item.status)
    )
      actions.append(
        button(t("revise"), () => void action(item, "revise"), "primary"),
      );
    if (reviewer && ["in_review", "approved"].includes(item.status)) {
      const note = input(area, t("note"), "", { type: "textarea", max: 1200 });
      if (item.status === "in_review") {
        area.append(el("p", t("reviewWarn"), "note"));
        const checks = el("div", undefined, "checks"),
          flags = {};
        for (const key of [
          "sourceRead",
          "hebrewChecked",
          "englishChecked",
          "scopeChecked",
        ]) {
          const l = el("label"),
            i = el("input");
          i.type = "checkbox";
          l.append(i, doc.createTextNode(t(key)));
          flags[key] = i;
          checks.append(l);
        }
        area.append(checks);
        const expires = input(
          area,
          t("expires"),
          new Date(Date.now() + 30 * 86400000).toISOString().slice(0, 10),
          { type: "date" },
        );
        actions.append(
          button(
            t("approve"),
            () =>
              void action(item, "approve", {
                note: note.value,
                expiresAt: expires.value + "T23:59:59Z",
                checks: Object.fromEntries(
                  Object.entries(flags).map(([k, n]) => [k, n.checked]),
                ),
              }),
            "primary",
          ),
          button(
            t("reject"),
            () => void action(item, "reject", { note: note.value }),
            "danger",
          ),
        );
      } else
        actions.append(
          button(
            t("withdraw"),
            () => void action(item, "withdraw", { note: note.value }),
            "danger",
          ),
        );
    }
    area.append(actions, el("h3", t("audit")));
    for (const event of item.events || []) {
      const row = el("div", undefined, "audit");
      row.append(
        el(
          "p",
          `${event.display_name || t("imported")} · ${event.professional_role || ""}`,
        ),
        el(
          "p",
          `${event.action} · ${new Date(event.occurred_at).toLocaleString(language)}`,
          "small",
        ),
      );
      if (event.note) row.append(el("p", event.note));
      area.append(row);
    }
  }
  function newDraft() {
    selected = undefined;
    const area = $("detail");
    area.replaceChildren(el("h2", t("new")), el("p", t("publicOnly"), "note"));
    const read = editFields(
      area,
      {
        topicId: "",
        domain: "general",
        title: { he: "", en: "" },
        body: { he: "", en: "" },
        scope: { he: "", en: "" },
        source: {
          url: "",
          publisher: "",
          checkedAt: new Date().toISOString().slice(0, 10),
          evidence: "",
        },
      },
      true,
    );
    area.append(
      button(
        t("save"),
        async () => {
          if (busy) return;
          busy = true;
          try {
            const value = await api("revisions", "POST", read());
            selected = value.id;
            await refresh();
            status(t("success"));
          } catch (e) {
            error(e);
          } finally {
            busy = false;
          }
        },
        "primary",
      ),
    );
    renderQueue();
  }
  async function preview() {
    try {
      const r = await fetcher("/staff/preview");
      if (!r.ok) return;
      const data = await r.json();
      $("preview").replaceChildren();
      for (const item of data.items) {
        const card = el("article", undefined, "card");
        card.append(
          el("span", t("draft"), "badge"),
          el("h3", item.title[language]),
          el("p", item.body[language]),
          link(item.source.url, t("source")),
          el("p", t("checked") + ": " + item.source.checkedAt, "small"),
        );
        $("preview").append(card);
      }
    } catch {
      status(t("error"), true);
    }
  }
  $("login").onsubmit = async (e) => {
    e.preventDefault();
    if (busy) return;
    busy = true;
    $("login-button").disabled = true;
    try {
      session = await api("login", "POST", {
        username: $("username").value,
        password: $("password").value,
      });
      $("password").value = "";
      showSession();
      $("detail").replaceChildren(el("p", t("choose")));
      await refresh();
      status("");
    } catch (e) {
      $("password").value = "";
      error(e);
    } finally {
      busy = false;
      $("login-button").disabled = false;
    }
  };
  $("logout").onclick = async () => {
    try {
      await api("logout", "POST", {});
      session = undefined;
      items = [];
      selected = undefined;
      detailGeneration++;
      $("detail").replaceChildren();
      $("queue").replaceChildren();
      showSession();
      status("");
    } catch (e) {
      error(e);
    }
  };
  $("language").onclick = () => {
    language = language === "he" ? "en" : "he";
    renderCopy();
    void preview();
    if (selected && session) void select(selected).catch(error);
  };
  $("filter").onchange = renderQueue;
  $("refresh").onclick = () => void refresh().catch(error);
  $("new").onclick = newDraft;
  renderCopy();
  void preview();
  void api("me")
    .then(async (s) => {
      session = s;
      showSession();
      $("detail").replaceChildren(el("p", t("choose")));
      await refresh();
    })
    .catch(() => {});
  return { getSession: () => session, refresh, select };
}
if (typeof document !== "undefined") mountDesk();
