'use strict';
// Regenerates knowledge-base-data.js from knowledge-base-full.json (the single source of truth),
// so the knowledge base also works offline and from file:// without a fetch.
// Run: node scripts/build-knowledge.cjs
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
const data = JSON.parse(fs.readFileSync(path.join(root, 'knowledge-base-full.json'), 'utf8'));
const enFile = path.join(root, 'knowledge-base-full.en.json');
const dataEn = fs.existsSync(enFile) ? JSON.parse(fs.readFileSync(enFile, 'utf8')) : null;
const out = '/* GENERATED by scripts/build-knowledge.cjs from knowledge-base-full.json (+ .en.json). Do not edit by hand. */\n' +
  '(function(root){root.MOMENTUM_KB_DATA=' + JSON.stringify(data) + ';root.MOMENTUM_KB_DATA_EN=' + JSON.stringify(dataEn) + ';})(typeof window==="undefined"?globalThis:window);\n';
fs.writeFileSync(path.join(root, 'knowledge-base-data.js'), out, 'utf8');
if (require.main === module) console.log('knowledge-base-data.js written (' + out.length + ' chars)');
module.exports = { data };
